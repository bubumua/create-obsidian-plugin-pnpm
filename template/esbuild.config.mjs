import esbuild from 'esbuild';
import process from 'node:process';
import { builtinModules } from 'node:module';
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// 获取命令行中带有 --out= 的参数，解析输出路径
const outArg = process.argv.find(arg => arg.startsWith("--out="));
const customPath = outArg ? outArg.replace("--out=", "") : null;
const defaultDir = prod ? "dist" : "./dist";
const targetDir = customPath ? path.resolve(customPath) : path.resolve(defaultDir);
// 自动拷贝插件至 Obsidian 插件目录
const copyFilesPlugin = {
	name: "copy-files-plugin",
	setup(build) {
		build.onEnd(() => {
			// 确保目标文件夹存在，不存在就自动创建
			if (!fs.existsSync(targetDir)) {
				fs.mkdirSync(targetDir, { recursive: true });
			}

			// 需要同步拷贝的文件列表
			const filesToCopy = ["manifest.json", "styles.css"];

			filesToCopy.forEach((file) => {
				if (fs.existsSync(file)) {
					fs.copyFileSync(file, path.join(targetDir, file));
				}
			});

			// 非生产环境下，自动生成/刷新 .hotreload 文件
			if (!prod) {
				const hotReloadFile = path.join(targetDir, ".hotreload");
				// 写入一个空文件，如果已存在也会刷新其修改时间，触发 hot-reload 检测
				fs.writeFileSync(hotReloadFile, "");
			}

			console.log(`[Plugin] Build finished! Files synced to: ${targetDir}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		'node:*',
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	minify: prod,
	outfile: path.join(targetDir, "main.js"),
	plugins: [copyFilesPlugin],
});

if (prod) {
	try {
		await context.rebuild();
	} finally {
		await context.dispose();
	}
} else {
	await context.watch();
}
